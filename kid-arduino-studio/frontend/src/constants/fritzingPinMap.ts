export function getFritzingPinCoordinate(part: string, pin: string): { x: number; y: number } | null {
  const normPart = part.toUpperCase().trim();
  const normPin = pin.toUpperCase().trim();

  if (normPart === 'ARDUINO_UNO' || normPart === 'ARDUINO') {
    if (FRITZING_UNO_PINS[normPin]) return FRITZING_UNO_PINS[normPin];
    if (normPin.startsWith('D') && FRITZING_UNO_PINS[normPin]) return FRITZING_UNO_PINS[normPin];
    if (!normPin.startsWith('D') && !isNaN(Number(normPin))) {
      const dPin = 'D' + normPin;
      if (FRITZING_UNO_PINS[dPin]) return FRITZING_UNO_PINS[dPin];
    }
    if (normPin === 'GND' || normPin === 'GROUND') return FRITZING_UNO_PINS['GND'];
    if (normPin === '5V') return FRITZING_UNO_PINS['5V'];
    if (normPin === '3V3' || normPin === '3.3V') return FRITZING_UNO_PINS['3V3'];
  }

  if (normPart === 'BREADBOARD') {
    if (FRITZING_BB_PINS[normPin]) return FRITZING_BB_PINS[normPin];
    if (normPin === 'RAIL_5V' || normPin === '5V' || normPin === 'VCC') return FRITZING_BB_PINS['RAIL_5V'];
    if (normPin === 'RAIL_GND' || normPin === 'GND') return FRITZING_BB_PINS['RAIL_GND'];
  }

  // Varsayılan breadboard deliği araması
  if (FRITZING_BB_PINS[normPin]) return FRITZING_BB_PINS[normPin];

  return null;
}
